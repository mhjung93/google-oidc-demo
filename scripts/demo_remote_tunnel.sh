#!/usr/bin/env bash
# 다른 컴퓨터(시연용 노트북)에서 zkWrapper 분리 데모를 쓰게 한다(2026-11-26 — 휴대폰 패스키(QR)는 블루투스가 있는 컴퓨터에서만 된다).
#   bash scripts/demo_remote_tunnel.sh <사용자@노트북주소>        # 이 PC 에서 실행. 켜 둔 동안만 이어진다(Ctrl+C 로 끊는다)
# 데모의 주소는 127.0.0.1 로 잡혀 있다(체인 :8547·:8548, Google 이 돌아오는 https://127.0.0.1:5100/google-relay, 탐색기 :4000·:4001) — 노트북의 브라우저가 그 주소를 부르면
# 노트북 자신에게 간다. 이 스크립트는 노트북의 그 포트들을 이 PC(와 서비스 VM)로 되돌려 잇는다(ssh 역방향 포워딩). 데모 설정·서버는 바꾸지 않는다.
# 노트북에 필요한 것(한 번):
#   1. ssh 서버(맥: 시스템 설정 → 공유 → 원격 로그인 / 윈도우: OpenSSH 서버).
#   2. hosts 에 한 줄:  127.0.0.1 zkwrapper.zkd.test zkone.zkd.test zktwo.zkd.test
#   3. 데모 CA 의 공개 인증서(.local/zkd-ca/ca.crt — 키가 아니다)를 신뢰하는 루트로 넣고 Chrome 을 다시 시작한다.
#   4. 블루투스를 켠다(휴대폰도). 휴대폰은 그 패스키가 있는 Google 계정으로 로그인돼 있어야 한다.
# 그다음 노트북의 Chrome 에서 https://zkone.zkd.test:3100 → "zkWrapper 로 로그인" → Google → "이미 있는 패스키로 로그인" → 다른 기기(QR).
set -u
[ $# -eq 1 ] || { sed -n '2,12p' "$0"; exit 2; }
RP1="${RP1_HOST:-192.168.226.11}"; RP2="${RP2_HOST:-192.168.226.12}"
exec ssh -N -o ExitOnForwardFailure=yes -o ServerAliveInterval=30 \
  -R 127.0.0.1:5100:127.0.0.1:5100 -R 127.0.0.1:8547:127.0.0.1:8547 -R 127.0.0.1:8548:127.0.0.1:8548 \
  -R 127.0.0.1:3100:"$RP1":3100 -R 127.0.0.1:3101:"$RP2":3101 \
  -R 127.0.0.1:4000:127.0.0.1:4000 -R 127.0.0.1:4001:127.0.0.1:4001 "$1"
